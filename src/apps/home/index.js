import React, {
    useCallback, useState, useEffect, useRef,
} from 'react'

import {
    View, Linking,
} from 'react-native'

import PropTypes from 'prop-types'

import Button, { BUTTON_TYPES } from '@ui/molecules/Button'
import Text, { TEXT_VARIATIONS } from '@ui/atoms/Text'

import { useStyles } from '@utils/customHooks/useStyles'
import { consoleLog } from '@utils/util'

import { useTranslation } from '../../i18n/hooks/useTranslation'

import { EVENTS } from '../../constants/events'
import { ROUTES } from '../../navigation/route.constants'

import { NextGameMenu } from '../arena/nextGameMenu'

import { HOME_PAGE_TEST_ID, CUSTOMIZE_EXPERIENCE_TOOLTIP_DISPLAY_DURATION_MS } from './home.constants'
import { getStyles } from './home.styles'
import { isAutoGeneratedPuzzleType } from '../arena/utils/util'
import { useDependency } from 'src/hooks/useDependency'
import { UpdateAppDialog } from '../components/UpdateAppDialog'
import { NAV_PARAMS } from '../../navigation/headerSection/headerSection.constants'
import { useCustomizeExperienceTooltip } from './hooks/useCustomizeExperienceTooltip'

const Home_ = ({ navigation }) => {
    const [pageHeight, setPageHeight] = useState(0)
    const [showNextGameMenu, setShowNextGameMenu] = useState(false)
    const tooltipHideTimeoutRef = useRef(null)

    const { t } = useTranslation('home')

    const styles = useStyles(getStyles)
    const dependencies = useDependency()
    const { show: showCustomizeTooltip, message: customizeTooltipMessage, markShown: markCustomizeTooltipShown } = useCustomizeExperienceTooltip(dependencies)

    useEffect(() => {
        if (!showCustomizeTooltip || !customizeTooltipMessage) return
        navigation.setParams({
            [NAV_PARAMS.SETTINGS_TOOLTIP]: {
                show: true,
                message: customizeTooltipMessage,
            },
        })
        if (tooltipHideTimeoutRef.current) clearTimeout(tooltipHideTimeoutRef.current)
        tooltipHideTimeoutRef.current = setTimeout(() => {
            navigation.setParams({
                [NAV_PARAMS.SETTINGS_TOOLTIP]: { show: false, message: '' },
            })
            tooltipHideTimeoutRef.current = null
        }, CUSTOMIZE_EXPERIENCE_TOOLTIP_DISPLAY_DURATION_MS)
        markCustomizeTooltipShown()
        return () => {
            if (tooltipHideTimeoutRef.current) clearTimeout(tooltipHideTimeoutRef.current)
        }
    }, [showCustomizeTooltip, customizeTooltipMessage, navigation, markCustomizeTooltipShown])

    useEffect(() => {
        // fetch('http://52.66.253.10:3000/getRecords')
        //     .then(response => response.json())
        //     .then(json => {
        //         console.log('@@@@@@ data', json)
        //     })
        //     .catch(err => {
        //         console.log('@@@@@', err.message)
        //         // setError(err.message);
        //     });
    }, []);

    const handlePlayOfflineClick = useCallback(() => {
        setShowNextGameMenu(true)
    }, [])

    const onParentLayout = useCallback(({ nativeEvent: { layout: { height = 0 } = {} } = {} }) => {
        setPageHeight(height)
    }, [])

    const onNewGameMenuClosed = useCallback(() => {
        setShowNextGameMenu(false)
    }, [])

    const handleMenuItemClicked = useCallback(
        item => {
            setShowNextGameMenu(false)
            if (isAutoGeneratedPuzzleType(item)) {
                navigation.navigate(ROUTES.LEVELS, { selectedGameMenuItem: item })
            } else {
                navigation.navigate(ROUTES.ARENA, { selectedGameMenuItem: item })
            }
        },
        [navigation],
    )

    const launchDeeplinkPuzzle = url => {
        navigation.navigate(ROUTES.ARENA, { puzzleUrl: url })
    }

    useEffect(() => {
        Linking.getInitialURL()
            .then(url => {
                url && launchDeeplinkPuzzle(url)
            })
            .catch(error => {
                consoleLog(error)
            })
    }, [])

    useEffect(() => {
        const handler = ({ url }) => {
            launchDeeplinkPuzzle(url)
        }
        const sub = Linking.addEventListener(EVENTS.LINKING_URL, handler)
        return () => sub?.remove()
    }, [])

    const renderSudokuText = () => (
        <Text
            type={TEXT_VARIATIONS.DISPLAY_LARGE}
            style={styles.gameDisplayName}
        >
            {t('gameTitle', "SUPER\nSUDOKU")}
        </Text>
    )

    const renderPlayButton = () => (
        <Button
            onPress={handlePlayOfflineClick}
            label={t('play', 'PLAY')}
            containerStyle={styles.playButtonContainer}
        />
    )

    const renderGameRulesCTA = () => (
        <Button
            type={BUTTON_TYPES.OUTLINED}
            label={t('howToPlay', 'How To Play ?')}
            containerStyle={styles.gameRulesCTA}
            onPress={() => navigation.navigate(ROUTES.PLAY_GUIDE)}
        />
    )

    const renderNewGameMenu = () => {
        if (!pageHeight || !showNextGameMenu) return null
        return (
            <NextGameMenu
                parentHeight={pageHeight}
                menuItemClick={handleMenuItemClicked}
                onMenuClosed={onNewGameMenuClosed}
            />
        )
    }

    // TODO: use <Page /> here
    return (
        <View
            testID={HOME_PAGE_TEST_ID}
            style={styles.container}
            onLayout={onParentLayout}
        >
            <View style={styles.viewContainer}>
                {renderSudokuText()}
                {renderPlayButton()}
                {renderGameRulesCTA()}
                <UpdateAppDialog />
            </View>
            {renderNewGameMenu()}
        </View>
    )
}

export const Home = React.memo(Home_)

Home_.propTypes = {
    navigation: PropTypes.object,
}

Home_.defaultProps = {
    navigation: {},
}
